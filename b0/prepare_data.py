"""Build a shared VOC-layout OWOD dataset without copying any images.

COCO conversion is executed from the supplied official converter, unchanged.
Only the official TOWOD (M-OWODB) split files are selected for B0.
"""
import argparse
from collections import Counter
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
from pathlib import Path
import runpy
import shutil
import xml.etree.ElementTree as ET

from PIL import Image

KNOWN = ['aeroplane', 'bicycle', 'bird', 'boat', 'bottle', 'bus', 'car',
         'cat', 'chair', 'cow', 'diningtable', 'dog', 'horse', 'motorbike',
         'person', 'pottedplant', 'sheep', 'sofa', 'train', 'tvmonitor']
ALIASES = dict(zip(['airplane', 'dining table', 'motorcycle', 'potted plant', 'couch', 'tv'],
                   ['aeroplane', 'diningtable', 'motorbike', 'pottedplant', 'sofa', 'tvmonitor']))


def link(source, target):
    if target.is_symlink() or target.exists():
        if target.resolve() != source.resolve():
            raise RuntimeError(f'Refuse to overwrite {target}')
    else:
        target.symlink_to(source.resolve())


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--datasets', type=Path, default=Path('/root/autodl-tmp/datasets'))
    p.add_argument('--output', type=Path, default=Path('/root/autodl-tmp/datasets/OWOD_B0'))
    p.add_argument('--artifacts', type=Path, default=Path('/root/autodl-tmp/experiments/B0_PROB_OWOBJ'))
    args = p.parse_args()
    repo = Path(__file__).resolve().parents[1]
    root = args.output
    for sub in ['JPEGImages', 'Annotations', 'ImageSets']:
        (root/sub).mkdir(parents=True, exist_ok=True)
    inventory = {}
    for folder in [args.datasets/'COCO2017/train2017', args.datasets/'COCO2017/val2017',
                   args.datasets/'VOC/VOC2007/JPEGImages', args.datasets/'VOC/VOC2012/JPEGImages']:
        paths = sorted(folder.glob('*.jpg'))
        inventory[str(folder)] = len(paths)
        if not paths:
            raise RuntimeError(f'Missing images: {folder}')
        for source in paths:
            link(source, root/'JPEGImages'/source.name)
    converter = runpy.run_path(str(repo/'datasets/coco2voc.py'))['coco_to_voc_detection']
    for split in ['train2017', 'val2017']:
        annotation = args.datasets/'COCO2017/annotations'/f'instances_{split}.json'
        marker = root/f'.converted_{split}.json'
        signature = hashlib.sha256(annotation.read_bytes()).hexdigest()
        if marker.exists():
            assert json.loads(marker.read_text())['sha256'] == signature
        else:
            # All XML in this new destination is generated by B0, never source data.
            converter(str(annotation), str(root))
            marker.write_text(json.dumps({'source': str(annotation), 'sha256': signature}))
    for year in ['VOC2007', 'VOC2012']:
        paths = sorted((args.datasets/'VOC'/year/'Annotations').glob('*.xml'))
        inventory[year+'_xml'] = len(paths)
        for source in paths:
            link(source, root/'Annotations'/source.name)
    split_hashes = {}
    for folder in ['TOWOD', 'OWDETR', 'VOC2007']:
        (root/'ImageSets'/folder).mkdir(exist_ok=True)
        for source in (repo/'data/OWOD/ImageSets'/folder).glob('*.txt'):
            dest = root/'ImageSets'/folder/source.name
            if dest.exists():
                assert dest.read_bytes() == source.read_bytes()
            else:
                shutil.copyfile(source, dest)
            split_hashes[str(dest.relative_to(root))] = hashlib.sha256(source.read_bytes()).hexdigest()

    def check(item):
        split, stem = item
        try:
            path = root/'JPEGImages'/f'{stem}.jpg'
            with Image.open(path) as image:
                image.load()  # Decode every Task 1 train/test image; no silent skipping.
                size = image.size
            tree = ET.parse(root/'Annotations'/f'{stem}.xml').getroot()
            xml_size = (int(tree.findtext('size/width')), int(tree.findtext('size/height')))
            assert size == xml_size, (size, xml_size)
            counts = Counter()
            for obj in tree.findall('object'):
                name = obj.findtext('name')
                name = ALIASES.get(name, name)
                group = 'known' if name in KNOWN else 'unknown'
                coords = [float(obj.findtext('bndbox/'+k)) for k in ['xmin','ymin','xmax','ymax']]
                x1,y1,x2,y2 = coords
                assert x2 >= x1 and y2 >= y1 and x1 >= 0 and y1 >= 0, coords
                # COCO official converter adds 1 to both corners; keep its convention.
                counts['boxes_above_image_plus_one'] += int(x2 > size[0]+1 or y2 > size[1]+1)
                counts[group+'_all'] += 1
                difficult = int(obj.findtext('difficult', '0'))
                counts[group+'_non_difficult'] += int(not difficult)
                counts['class:'+name] += 1
            counts['images'] += 1
            return split, counts, None
        except Exception as e:
            return split, Counter(), {'image': stem, 'split': split, 'error': repr(e)}

    items, summary, ids, duplicates = [], {}, {}, {}
    for split in ['owod_t1_train', 'owod_all_task_test']:
        names = (root/'ImageSets/TOWOD'/f'{split}.txt').read_text().splitlines()
        duplicates[split] = {'rows':len(names), 'unique_images':len(set(names)),
                             'extra_rows':len(names)-len(set(names))}
        # Official M-OWODB test contains repeated COCO IDs. Keep the file and
        # evaluator behavior unchanged, and report both row and unique counts.
        ids[split] = set(names)
        summary[split] = Counter()
        items.extend((split, x) for x in names)
    assert not ids['owod_t1_train'] & ids['owod_all_task_test'], 'Train/test overlap'
    errors = []
    with ThreadPoolExecutor(max_workers=8) as pool:
        for i, (split, counts, error) in enumerate(pool.map(check, items)):
            summary[split].update(counts)
            if error:
                errors.append(error)
            if i % 2000 == 0:
                print(f'Validated {i}/{len(items)}, errors={len(errors)}', flush=True)
    report = {'dataset_root': str(root), 'inventory': inventory, 'split_sha256': split_hashes,
              'split_rows_and_unique':duplicates,
              'known_classes': KNOWN, 'splits': summary, 'errors': errors,
              'train_test_overlap': 0, 'image_storage': 'absolute symlinks; original images untouched',
              'conversion': 'unchanged official datasets/coco2voc.py; integer coordinates, crowd kept',
              'unknown_definition': 'annotated objects from the other 60 COCO classes; no unlabeled regions',
              'training': 'loader removes unknown instances; unknown GT used only offline',
              'disk_free_bytes': shutil.disk_usage(root).free}
    target = args.artifacts/'reports/data_audit.json'
    target.write_text(json.dumps(report, indent=2, ensure_ascii=False))
    print(json.dumps(report, indent=2, ensure_ascii=False), flush=True)
    if errors:
        raise RuntimeError(f'{len(errors)} failed images; see {target}')


if __name__ == '__main__':
    main()
